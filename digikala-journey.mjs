// DigiKala replay journey for Browsertime 28.0.0.
// Seeded, bounded variation of the previously recorded DigiKala browsing journey.
// Two independent browser slots. Product URLs and the READY/START protocol remain unchanged.
import net from 'node:net';
import { readFileSync } from 'node:fs';

const urls = {
  home: 'https://www.digikala.com/',
  category: 'https://www.digikala.com/search/category-mobile-phone/',
  s25: 'https://www.digikala.com/product/dkp-20135132/?product_id=20135132&variant_id=87155137',
  a07: 'https://www.digikala.com/product/dkp-20109389/?product_id=20109389&variant_id=73241290',
  iphone: 'https://www.digikala.com/product/dkp-20127115/?product_id=20127115&variant_id=75156356',
};

const categoryPattern = [
  { pixels: 280, delay: 760 },
  { pixels: 220, delay: 900 },
  { pixels: 340, delay: 700 },
  { pixels: 180, delay: 1500 },
  { pixels: 310, delay: 850 },
  { pixels: 260, delay: 800 },
];

const productPattern = [
  { pixels: 280, delay: 850 },
  { pixels: 400, delay: 750 },
  { pixels: 260, delay: 950 },
  { pixels: 380, delay: 850 },
  { pixels: 260, delay: 1700 },
  { pixels: 460, delay: 780 },
  { pixels: 320, delay: 850 },
  { pixels: 380, delay: 900 },
  { pixels: 260, delay: 1350 },
  { pixels: 440, delay: 750 },
  { pixels: 350, delay: 870 },
  { pixels: 260, delay: 800 },
  { pixels: 400, delay: 1600 },
  { pixels: 320, delay: 900 },
  { pixels: 380, delay: 750 },
  { pixels: 260, delay: 900 },
  { pixels: 400, delay: 950 },
];

// The seed is read once per browser at launch. The root-level text file is
// available inside the existing read-only /sitespeed.io Docker bind mount.
// An environment variable can override it for independent command-line tests.
const DEFAULT_SEED = 101;
const START_SPACING_MS = 5000; // Browser 2 begins about five seconds after browser 1.
const START_JITTER_MS = 1200;

function readTrafficSeed() {
  let value = process.env.BROWSER_TRAFFIC_SEED;
  if (value === undefined) {
    try {
      value = readFileSync(new URL('./traffic-seed.txt', import.meta.url), 'utf8').trim();
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      value = String(DEFAULT_SEED);
    }
  }
  if (!/^[0-9]+$/.test(value) || Number(value) > 0xffffffff) {
    throw new Error('Traffic seed must be an unsigned 32-bit decimal integer');
  }
  return Number(value) >>> 0;
}

// Mulberry32: stable pseudo-random sequence, not Math.random().
function seededRandom(seed) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let x = state;
    x = Math.imul(x ^ (x >>> 15), x | 1);
    x ^= x + Math.imul(x ^ (x >>> 7), x | 61);
    return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
  };
}

function randomInt(random, min, max) {
  return min + Math.floor(random() * (max - min + 1));
}

function vary(random, original, fraction, minimum = 1) {
  const delta = Math.round(original * fraction);
  return Math.max(minimum, original + randomInt(random, -delta, delta));
}

function makePlan(seed, slot) {
  // Each Chrome instance gets a different but reproducible random stream.
  const random = seededRandom((seed ^ Math.imul(slot, 0x9e3779b9)) >>> 0);
  const startOffsetMs = Math.max(
    0,
    (slot - 1) * START_SPACING_MS + randomInt(random, -START_JITTER_MS, START_JITTER_MS)
  );
  const scrolls = (pattern) => pattern.map(({ pixels, delay }) => ({
    pixels: vary(random, pixels, 0.15, 50),
    delay: vary(random, delay, 0.20, 200),
  }));
  return {
    startOffsetMs,
    homeWaitMs: vary(random, 2500, 0.20, 1500),
    categoryScrolls: Array.from({ length: 3 }, () => scrolls(categoryPattern)),
    products: ['s25', 'a07', 'iphone'].map((key) => ({
      key,
      beforeScrollMs: vary(random, 2000, 0.25, 1000),
      afterScrollMs: vary(random, 2000, 0.25, 1000),
      scrolls: scrolls(productPattern),
    })),
  };
}

/**
 * Control connection to Tester, over host loopback (Docker --network host).
 * READY means the custom script was invoked after WebDriver initialized Chrome.
 * START is required before the script makes its first DigiKala request.
 * No browser traffic is generated by this control connection.
 */
async function waitForExperimentStart(slot, port) {
  if (!Number.isSafeInteger(slot) || slot < 1 || slot > 2) {
    throw new Error('BROWSER_SLOT must be 1 or 2 for this experiment');
  }
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error('BROWSER_CONTROL_PORT must be a TCP port');
  }

  await new Promise((resolve, reject) => {
    const socket = net.createConnection({ host: '127.0.0.1', port });
    let settled = false;
    let incoming = '';

    function finish(error) {
      if (settled) return;
      settled = true;
      socket.removeAllListeners();
      socket.destroy();
      if (error) reject(error);
      else resolve();
    }

    // No per-browser 120s deadline: early Chrome instances can wait while
    // any number of later instances launch. Tester owns the readiness timeout
    // and closes this socket if preparation fails or is cancelled.
    socket.on('connect', () => socket.write(`READY ${slot}\n`));
    socket.on('error', (error) => finish(error));
    socket.on('end', () => finish(new Error('Tester closed the control connection')));
    socket.on('close', () => finish(new Error('Control connection closed before START')));
    socket.on('data', (chunk) => {
      incoming += chunk.toString('utf8');
      if (incoming.length > 1024) {
        finish(new Error('Unexpected control message length'));
        return;
      }
      while (incoming.includes('\n')) {
        const index = incoming.indexOf('\n');
        const line = incoming.slice(0, index).trim();
        incoming = incoming.slice(index + 1);
        if (line === 'START') {
          finish();
          return;
        }
        if (line === 'STOP') {
          finish(new Error('Experiment cancelled before START'));
          return;
        }
        finish(new Error(`Unexpected command from Tester: ${line}`));
        return;
      }
    });
  });
}

export default async function (context, commands) {
  const slot = Number(process.env.BROWSER_SLOT ?? '1');
  if (!Number.isSafeInteger(slot) || slot < 1 || slot > 2) {
    throw new Error('BROWSER_SLOT must be 1 or 2 for this experiment');
  }
  const controlPort = process.env.BROWSER_CONTROL_PORT;
  const seed = readTrafficSeed();
  const plan = makePlan(seed, slot);

  // Standalone runs still work. Managed runs use the existing READY/START handshake.
  if (controlPort !== undefined) {
    context.log.info(`Browser ${slot} initialized: sending READY, awaiting START`);
    await waitForExperimentStart(slot, Number(controlPort));
    context.log.info(`Browser ${slot} received START`);
  }

  // START is the shared experiment signal; navigation is deliberately staggered.
  // Planned timings depend ONLY on seed and slot, not previous request durations.
  const startTime = performance.now();
  let categoryPosition = 0;
  let categoryIndex = 0;
  let measurementStarted = false;
  context.log.info(
    `Browser ${slot} plan: seed=${seed} startOffset=${plan.startOffsetMs}ms ` +
    `products=${plan.products.map((item) => item.key).join(',')}`
  );

  async function scrollPattern(pattern) {
    for (const step of pattern) {
      await commands.js.run(
        `window.scrollBy({ top: ${step.pixels}, behavior: 'smooth' });`
      );
      await commands.wait.byTime(step.delay);
    }
  }

  async function browseCategory() {
    await scrollPattern(plan.categoryScrolls[categoryIndex++]);
    categoryPosition = await commands.js.run('return window.scrollY;');
  }

  async function inspectProduct(product, label) {
    context.log.info(`Browser ${slot}: open ${label}`);
    await commands.navigate(urls[product.key]);
    await commands.wait.byTime(product.beforeScrollMs);
    await scrollPattern(product.scrolls);
    await commands.wait.byTime(product.afterScrollMs);
  }

  async function backToCategory() {
    await commands.navigation.back({ waitForNavigation: true });
    const path = await commands.js.run('return window.location.pathname;');
    if (!path.includes('/search/category-mobile-phone/')) {
      throw new Error('Back navigation did not return to the phone category');
    }
    const current = await commands.js.run('return window.scrollY;');
    if (current < categoryPosition - 100) {
      await commands.js.run(`window.scrollTo(0, ${categoryPosition});`);
    }
    // Every category visit scrolls before the next recorded product opens.
    await browseCategory();
  }

  try {
    if (plan.startOffsetMs > 0) {
      await commands.wait.byTime(plan.startOffsetMs);
    }
    await commands.measure.start(`digikala-shopping-browser-${slot}`);
    measurementStarted = true;

    await commands.navigate(urls.home);
    await commands.wait.byTime(plan.homeWaitMs);
    await commands.navigate(urls.category);
    await browseCategory();

    await inspectProduct(plan.products[0], 'Samsung Galaxy S25 FE');
    await backToCategory();
    await inspectProduct(plan.products[1], 'Samsung Galaxy A07');
    await backToCategory();
    await inspectProduct(plan.products[2], 'Apple iPhone 17');
  } finally {
    const elapsed = ((performance.now() - startTime) / 1000).toFixed(1);
    context.log.info(`Browser ${slot} journey elapsed after START: ${elapsed}s`);
    if (measurementStarted) await commands.measure.stop();
  }
}
